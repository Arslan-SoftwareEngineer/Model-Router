"""Lightweight output verification infrastructure.

Inspects generated candidate responses to ensure educational pedagogical standards,
factual completeness, and reasoning depth before returning to students.
Escalates to frontier models when speculative fast SLM outputs do not meet criteria.
"""

from __future__ import annotations

from typing import Any, Dict, Optional


class VerificationResult:
    """Encapsulates output verification status and diagnostic reasoning."""

    def __init__(self, is_valid: bool, reason: str = "") -> None:
        self.is_valid = bool(is_valid)
        self.reason = reason

    def __bool__(self) -> bool:
        return self.is_valid

    def __repr__(self) -> str:
        return f"VerificationResult(is_valid={self.is_valid}, reason='{self.reason}')"

    def to_dict(self) -> Dict[str, Any]:
        return {"is_valid": self.is_valid, "reason": self.reason}


class LightweightVerifier:
    """Evaluates candidate model outputs against quality and complexity criteria."""

    def __init__(self, min_tier1_words: int = 3, min_tier2_words: int = 10, min_tier3_words: int = 40):
        self.min_tier1_words = min_tier1_words
        self.min_tier2_words = min_tier2_words
        self.min_tier3_words = min_tier3_words

    def verify(
        self,
        prompt: str,
        response: str,
        tier: int = 1,
        force_fail: bool = False,
        model_name: Optional[str] = None,
    ) -> VerificationResult:
        """Verify model output quality.

        Args:
            prompt: Original user/student prompt.
            response: Generated candidate response text.
            tier: Query complexity tier (1, 2, or 3).
            force_fail: If True, forces verification failure for demo purposes.
            model_name: The model that produced the candidate output.

        Returns:
            VerificationResult: boolean-evaluable object with diagnostic reason.
        """
        if force_fail:
            return VerificationResult(
                is_valid=False,
                reason="Simulated verification failure (force_fallback_demo=True)",
            )

        # Baseline sanity checks
        if not response or not response.strip():
            return VerificationResult(is_valid=False, reason="Empty or whitespace-only response")

        text = response.strip()
        word_count = len(text.split())

        # Check for obvious refusal or catastrophic failure patterns
        error_indicators = ["[error]", "failed to generate", "cannot assist with this"]
        for ind in error_indicators:
            if ind in text.lower():
                return VerificationResult(is_valid=False, reason=f"Response contains failure marker: '{ind}'")

        # Tier 1 checks (Factual Recall)
        if tier == 1:
            if word_count < self.min_tier1_words:
                return VerificationResult(
                    is_valid=False,
                    reason=f"Tier 1 output too brief ({word_count} words < minimum {self.min_tier1_words})",
                )
            return VerificationResult(is_valid=True, reason="Tier 1 factual verification passed")

        # Tier 2 checks (Conceptual Explanation / Synthesis)
        if tier == 2:
            if word_count < self.min_tier2_words:
                return VerificationResult(
                    is_valid=False,
                    reason=f"Tier 2 output lacks sufficient explanatory depth ({word_count} words < {self.min_tier2_words})",
                )
            return VerificationResult(is_valid=True, reason="Tier 2 conceptual synthesis verification passed")

        # Tier 3 checks (Complex Multi-step Reasoning / Proofs)
        if tier == 3:
            # Speculative fast attempts on Tier 3 with 8B models require rigorous proof markers
            # If generated by speculative 8B model or mock response without deep reasoning:
            proof_markers = ["step", "proof", "therefore", "hence", "because", "induction", "base case"]
            has_proof_structure = any(marker in text.lower() for marker in proof_markers)

            if word_count < self.min_tier3_words or not has_proof_structure:
                return VerificationResult(
                    is_valid=False,
                    reason=(
                        f"Tier 3 speculative response failed verification: "
                        f"Insufficient reasoning depth ({word_count} words) or missing step-by-step proof markers. "
                        f"Requires escalation to 70B frontier architecture."
                    ),
                )

            return VerificationResult(is_valid=True, reason="Tier 3 reasoning verification passed")

        return VerificationResult(is_valid=True, reason="Default verification passed")
